-- SAFE ADDITIVE SETUP. Run once in Supabase SQL Editor.
-- Does not alter existing attendance or user accounts.
BEGIN;
CREATE TABLE IF NOT EXISTS public.teams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
INSERT INTO public.teams(name) VALUES
 ('HR and Admin'),('Development Team'),('Quality Assurance Team'),
 ('Software Support Team'),('ACE/ACI Support Team')
ON CONFLICT (name) DO NOTHING;
ALTER TABLE public.employees ADD COLUMN IF NOT EXISTS team_id bigint REFERENCES public.teams(id);
CREATE INDEX IF NOT EXISTS employees_team_id_idx ON public.employees(team_id);
CREATE TABLE IF NOT EXISTS public.user_team_roles (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  team_id bigint REFERENCES public.teams(id),
  role text NOT NULL CHECK (role IN ('member','leader','hr_viewer')),
  CONSTRAINT user_team_roles_valid CHECK ((role='hr_viewer' AND team_id IS NULL) OR (role IN ('member','leader') AND team_id IS NOT NULL)),
  CONSTRAINT user_team_roles_unique UNIQUE NULLS NOT DISTINCT (user_id,team_id,role)
);
CREATE INDEX IF NOT EXISTS user_team_roles_user_idx ON public.user_team_roles(user_id);
ALTER TABLE public.teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_team_roles ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS teams_authenticated_read ON public.teams;
CREATE POLICY teams_authenticated_read ON public.teams FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS team_roles_self_read ON public.user_team_roles;
CREATE POLICY team_roles_self_read ON public.user_team_roles FOR SELECT TO authenticated USING (user_id=(select auth.uid()) OR (select public.is_admin()));
-- No client-side write policy for roles: assignments must be performed by a trusted admin in SQL Editor.
CREATE OR REPLACE FUNCTION public.can_view_team(target_team bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT public.is_admin()
 OR EXISTS (SELECT 1 FROM public.user_team_roles r WHERE r.user_id=(select auth.uid()) AND r.role='hr_viewer')
 OR EXISTS (SELECT 1 FROM public.user_team_roles r WHERE r.user_id=(select auth.uid()) AND r.team_id=target_team AND r.role IN ('member','leader'));
$$;
CREATE OR REPLACE FUNCTION public.can_edit_team(target_team bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT public.is_admin()
 OR EXISTS (SELECT 1 FROM public.user_team_roles r WHERE r.user_id=(select auth.uid()) AND r.team_id=target_team AND r.role='leader');
$$;
REVOKE ALL ON FUNCTION public.can_view_team(bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.can_edit_team(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.can_view_team(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.can_edit_team(bigint) TO authenticated;

-- Only administrators and the designated HR and Admin team leader may manage employee records.
CREATE OR REPLACE FUNCTION public.can_manage_employees()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT public.is_admin() OR EXISTS (
   SELECT 1 FROM public.user_team_roles r
   JOIN public.teams t ON t.id=r.team_id
   WHERE r.user_id=(select auth.uid()) AND r.role='leader' AND t.name='HR and Admin'
 );
$$;
REVOKE ALL ON FUNCTION public.can_manage_employees() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.can_manage_employees() TO authenticated;
COMMIT;
